"""Carry matching translations of old shared controls into the new interface."""
import json
import re
from pathlib import Path

app = Path(__file__).resolve().parents[1]
source = app.parent / 'lib/l10n'
english = json.loads((source / 'app_en.arb').read_text())
keys = {value: key for key, value in english.items() if isinstance(value, str)}
keys.update({'Choose your path': 'flowChoose', 'Find a match': 'flowMatch',
             'Edit birth details': 'flowBirthDetails', 'Chart tools': 'flowTools',
             'Ask about this': 'flowAskReading', 'Four pillar details': 'flowDetails',
             'Save birth details': 'flowBirthDetails', 'Add my birth details': 'flowAddBirth'})
texts = {'My reading', 'Match', 'Ask Agent'}
for path in (app / 'src').rglob('*.vue'):
    texts.update(re.findall(r"""tr\(\s*['"]([^'"\n]+)['"]\s*,""", path.read_text()))
languages, labels = [], {}
for path in sorted(source.glob('app_*.arb')):
    locale = path.stem[4:].replace('_', '-')
    words = json.loads(path.read_text())
    languages.append([locale, words['languageName']])
    if locale not in ['en', 'zh']:
        labels[locale] = {text: words[keys[text]] for text in sorted(texts)
                          if text in keys and keys[text] in words and words[keys[text]] != text}
out = 'export const languages = ' + json.dumps(languages, ensure_ascii=False) + '\n'
out += 'export const labels = ' + json.dumps(labels, ensure_ascii=False, separators=(',', ':')) + '\n'
(app / 'src/lib/translations.js').write_text('// Generated by scripts/pack-labels.py\n' + out)
