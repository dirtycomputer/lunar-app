class TermTap extends StatelessWidget {
  final String termId;
  final Widget child;
  final String? contextText;
  final BorderRadius radius;
  const TermTap(
      {super.key,
      required this.termId,
      required this.child,
      this.contextText,
      this.radius = const BorderRadius.all(Radius.circular(8))});
  @override
  Widget build(BuildContext context) {
    final term = glossary[termId];
    if (term == null) return child;
    return Semantics(
        button: true,
        label: 'Explain ${term.title}',
        child: Tooltip(
            message: 'Explain ${term.title}',
            child: Material(
                color: Colors.transparent,
                child: InkWell(
                    borderRadius: radius,
                    onTap: () => showTermExplanation(context, termId,
                        contextText: contextText),
                    child: child))));
  }
}

class TermLink extends StatelessWidget {
  final String termId, label;
  final String? contextText;
  final TextStyle? style;
  final TextAlign align;
  const TermLink(
      {super.key,
      required this.termId,
      required this.label,
      this.contextText,
      this.style,
      this.align = TextAlign.start});
  @override
  Widget build(BuildContext context) => TermTap(
      termId: termId,
      contextText: contextText,
      child: Padding(
          padding: const EdgeInsets.symmetric(vertical: 8, horizontal: 3),
          child: Text(label,
              textAlign: align,
              style: (style ??
                      const TextStyle(
                          fontSize: 12, fontWeight: FontWeight.w600))
                  .copyWith(
                      color: style?.color ?? blue,
                      decoration: TextDecoration.underline,
                      decorationStyle: TextDecorationStyle.dotted,
                      decorationColor:
                          (style?.color ?? blue).withValues(alpha: .5)))));
}

